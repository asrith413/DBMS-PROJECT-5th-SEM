from __future__ import annotations

from typing import Any

import streamlit as st

from components.ui import (
    count_chart,
    handle_api_error,
    metric_grid,
    page_header,
    require_role,
    show_flash,
)
from services.api_client import APIClient, APIError


def render_reports(api: APIClient, user: dict[str, Any]) -> None:
    if not require_role(user, {"ADMIN"}):
        return
    show_flash("reports")
    page_header(
        "Executive reporting",
        "Reports",
        "Review organization-wide incident distribution, trends, analyst workload, and export the API report.",
    )

    try:
        report = api.dashboard_report()
    except APIError as error:
        handle_api_error(error, "Unable to load report")
        return

    metric_grid(
        [
            ("Total incidents", report.get("total_incidents", 0)),
            ("Active", report.get("open_incidents", 0)),
            ("Resolved / closed", report.get("resolved_incidents", 0)),
            ("Critical", report.get("critical_incidents", 0)),
            ("SLA breaches", report.get("sla_breaches", 0)),
            ("Analysts", report.get("analyst_count", 0)),
        ]
    )

    st.subheader("Incident composition")
    first, second = st.columns(2)
    with first:
        st.caption("BY SEVERITY")
        count_chart(report.get("incidents_by_severity", []))
    with second:
        st.caption("BY STATUS")
        count_chart(report.get("incidents_by_status", []))

    first, second = st.columns(2)
    with first:
        st.caption("BY INCIDENT TYPE")
        count_chart(report.get("incidents_by_type", []))
    with second:
        st.caption("MONTHLY TREND")
        count_chart(report.get("monthly_trends", []))

    st.subheader("Analyst workload")
    count_chart(report.get("analyst_workload", []), height=260)

    st.subheader("CSV export")
    st.caption(
        "The export is generated by GET /reports/incidents.csv and includes incident, status, severity, type, reporter, and dates."
    )
    try:
        csv_data = api.export_incidents_csv()
    except APIError as error:
        handle_api_error(error, "Unable to generate CSV export")
    else:
        st.download_button(
            "Download incident report (CSV)",
            data=csv_data,
            file_name="cims_incidents.csv",
            mime="text/csv",
            type="primary",
            use_container_width=True,
        )
