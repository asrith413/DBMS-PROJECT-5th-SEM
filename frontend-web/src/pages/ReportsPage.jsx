import { useEffect, useState } from 'react'
import {
  Activity,
  CircleCheckBig,
  Download,
  FileSpreadsheet,
  RefreshCw,
  ShieldAlert,
  Siren,
  Users,
} from 'lucide-react'

import Button from '../components/common/Button'
import PageHeader from '../components/common/PageHeader'
import StatCard from '../components/common/StatCard'
import { ErrorState, LoadingState } from '../components/common/States'
import ReportsCharts from '../components/reports/ReportsCharts'
import SlaSummary from '../components/reports/SlaSummary'
import { useToast } from '../context/ToastContext'
import { api } from '../services/api'
import { toCsvDownload } from '../utils/format'

export default function ReportsPage() {
  const { notify } = useToast()
  const [report, setReport] = useState(null)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState(null)
  const [revision, setRevision] = useState(0)
  const [downloading, setDownloading] = useState(false)

  useEffect(() => {
    let active = true
    setLoading(true)
    setError(null)
    api.reports.dashboard()
      .then((data) => {
        if (active) setReport(data)
      })
      .catch((requestError) => {
        if (active) setError(requestError)
      })
      .finally(() => {
        if (active) setLoading(false)
      })
    return () => { active = false }
  }, [revision])

  const downloadCsv = async () => {
    setDownloading(true)
    try {
      const response = await api.reports.csv()
      toCsvDownload(response, 'cims_incidents.csv')
      notify('Incident CSV downloaded.', 'success')
    } catch (requestError) {
      notify(requestError.message, 'error')
    } finally {
      setDownloading(false)
    }
  }

  return (
    <div>
      <PageHeader
        eyebrow="Executive reporting"
        title="Reports"
        description="Organization-wide incident metrics, workload, trends, and authenticated exports from the reporting API."
        actions={(
          <Button variant="secondary" icon={RefreshCw} loading={loading} onClick={() => setRevision((value) => value + 1)}>
            Refresh
          </Button>
        )}
      />

      {loading && !report ? (
        <div className="panel"><LoadingState label="Building dashboard report..." /></div>
      ) : error ? (
        <ErrorState error={error} title="Unable to load report" onRetry={() => setRevision((value) => value + 1)} />
      ) : report ? (
        <>
          <section className="grid gap-3 sm:grid-cols-2 xl:grid-cols-3 2xl:grid-cols-6" aria-label="Dashboard metrics">
            <StatCard label="Total incidents" value={report.total_incidents} icon={ShieldAlert} tone="blue" detail="All recorded incidents" />
            <StatCard label="Active" value={report.open_incidents} icon={Activity} tone="cyan" detail="Not resolved or closed" />
            <StatCard label="Resolved / closed" value={report.resolved_incidents} icon={CircleCheckBig} tone="green" detail="Terminal workflow states" />
            <StatCard label="Critical" value={report.critical_incidents} icon={Siren} tone="red" detail="All incident states" />
            <StatCard label="SLA breaches" value={report.sla_breaches} icon={Siren} tone="yellow" detail="API-calculated breach count" />
            <StatCard label="Analysts" value={report.analyst_count} icon={Users} tone="blue" detail="Analyst profiles" />
          </section>

          <SlaSummary total={report.total_incidents} breaches={report.sla_breaches} />
          <ReportsCharts report={report} />

          <section className="panel mt-5 overflow-hidden">
            <div className="grid items-center gap-5 p-5 md:grid-cols-[auto_minmax(0,1fr)_auto]">
              <div className="grid h-12 w-12 place-items-center rounded-xl border border-emerald-500/30 bg-emerald-500/10 text-emerald-300">
                <FileSpreadsheet className="h-6 w-6" />
              </div>
              <div>
                <h2 className="font-semibold text-white">Incident report CSV</h2>
                <p className="mt-1 text-sm leading-6 text-slate-400">Generated by the authenticated reports endpoint with incident ID, title, status, severity, type, reporter, and reported/resolved dates.</p>
              </div>
              <Button icon={Download} loading={downloading} onClick={downloadCsv} className="w-full md:w-auto">
                Download CSV
              </Button>
            </div>
          </section>
        </>
      ) : null}
    </div>
  )
}
